/**
 * Ввод игрока за кадр: общий вид для клавиатуры с мышью и для тача. Игрок только ходит, смотрит
 * и светит — кнопок действия нет.
 */
export interface InputFrame {
  /** Движение в осях игрока: x — вправо, z — вперёд; длина до 1. */
  moveX: number;
  moveZ: number;
  run: boolean;
  /** Поворот луча за кадр, радианы: yaw — влево положительный, pitch — вверх положительный. */
  lookYaw: number;
  lookPitch: number;
  /** Выключатель фонаря нажат в этом кадре: компьютер — F или левая кнопка мыши, телефон — короткий тап по кнопке фонаря. */
  light: boolean;
  /**
   * Палец держат на кнопке фонаря (телефон; не нажатие, а состояние): пока держат, фонарь заряжается, полный —
   * вспышка и свет (слова партнёра 17.11 08:42).
   */
  crank: boolean;
  /** Запрошена пауза. */
  pause: boolean;
}

/**
 * Разовое нажатие (щелчок фонаря) доживает до ближайшего шага игры. Игра идёт шагами по 1/60 с, а экран 120 Гц
 * (MacBook, iPhone Pro) рисует вдвое чаще: каждый второй кадр проходит без шага, и нажатие, пришедшее в такой кадр,
 * пропадало — фонарь включался «через раз» (слова партнёра 17.11: «кнопка включения и выключения фонаря должна работать
 * по 1 нажатию»). Вызывать раз в кадр: pressed — нажатие этого кадра, steps — сколько шагов игры будет в кадре.
 * Возвращает, нажат ли выключатель на первом шаге кадра; остальное помнит до следующего кадра.
 */
export class PressCarry {
  private held = false;

  take(pressed: boolean, steps: number): boolean {
    const p = pressed || this.held;
    this.held = p && steps === 0;
    return p && steps > 0;
  }
}

export function emptyInput(): InputFrame {
  return { moveX: 0, moveZ: 0, run: false, lookYaw: 0, lookPitch: 0, light: false, crank: false, pause: false };
}

export interface InputSource {
  /** Забрать накопленный ввод (счётчики нажатий и поворота обнуляются). */
  poll(): InputFrame;
  /** Сбросить всё зажатое (пауза, потеря фокуса). */
  release(): void;
  dispose(): void;
}
