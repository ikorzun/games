/**
 * Цвет «камеры» у места (POST_FRAG): оттенки теней и светов и сколько цвета остаётся. Отдельно от
 * render/renderer.ts, чтобы игра и тесты брали числа без three.js.
 */
import type { Vec3 } from '../core/types';

export interface Grade {
  /** Оттенок теней. */
  lo: Vec3;
  /** Оттенок светов. */
  hi: Vec3;
  /** Сколько цвета остаётся: 1 — весь, меньше — кадр обесцвечен. */
  sat: number;
}

/** Цвет убежища — с него начиналась «дешёвая камера»: болотные тени, жёлтые света, четверть цвета снята. */
export const GRADE_DEFAULT: Grade = { lo: [0.9, 1.0, 0.93], hi: [1.03, 1.0, 0.92], sat: 0.74 };

/** Сила колец дешёвого отражателя вокруг пятна фонаря — как в убежище. */
export const RINGS_DEFAULT = 0.08;
