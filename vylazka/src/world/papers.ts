/**
 * Бумага: настоящие листы на стенах, в рамках и на потолке — старые студийные портреты, деньги и
 * облигации стран, которых больше нет, карты. Это фотографии, которые присылает партнёр (слова партнёра:
 * «Используй для локаций, разрешения автора есть. Еще я буду периодически скидывать фотки объектов или
 * стен, решай сам что переделать в 3д, а что оставить плоским на стене или в рамке или на потолке»).
 *
 * Плоским остаётся то, что и в жизни плоское: фотография, купюра, карта. Объёмное (чемоданы) собирается
 * из геометрии — world/props_luggage.ts.
 *
 * Листы лежат слоями одной текстуры-стопки (render/paper_images.ts): слой — файл assets/papers/<id>.webp,
 * 720 × 1280. Лист — слой целиком или его часть (портрет в рамке — кусок стены портретов). Здесь только
 * данные и раскладка — чистый TS, без canvas: уровень собирается и в тестах.
 *
 * Лица не сохраняются (решение основной модели; последняя вещь убежища — «the faces did not save»):
 * издали на листе портреты, вблизи лицо расплывается, а одежда, поза и фон студии остаются. У слоёв
 * портретов для этого в альфа-канале лежит маска лиц; размывает шейдер (render/shaders.ts, uPapers).
 *
 * Что на листах, чего в них нет и почему — assets/papers/README.md.
 */

/** Размер слоя, px. Портретный кадр телефона, 9 : 16. */
export const PAPER_W = 720;
export const PAPER_H = 1280;

/**
 * Слои по порядку: номер слоя — место в списке. Файл — assets/papers/<id>.webp. Портреты идут первыми:
 * шейдер узнаёт их по номеру слоя (меньше PAPER_FACES) и читает маску лиц из альфа-канала.
 */
export const PAPER_LAYERS = ['faces_a', 'faces_b', 'faces_c', 'money', 'notgeld', 'bonds', 'map_union'] as const;
export type PaperLayer = (typeof PAPER_LAYERS)[number];
/** Сколько первых слоёв — портреты. */
export const PAPER_FACES = 3;

export type PaperKind =
  /** Стена лиц: студийные портреты столетней давности. */
  | 'faces'
  /** Один портрет — в рамку. */
  | 'face'
  /** Деньги, которые ничего не стоят. */
  | 'money'
  /** Акция или облигация — в рамку. */
  | 'bond'
  /** Карта. */
  | 'map';

export interface PaperDef {
  id: string;
  kind: PaperKind;
  layer: PaperLayer;
  /** Место в слое, px: x, y — левый верхний угол. */
  x: number;
  y: number;
  w: number;
  h: number;
  /** Ширина на стене, м (высота — по пропорции). */
  width: number;
  /** Коротко по-русски: что на листе. */
  ru: string;
}

const def = (id: string, kind: PaperKind, layer: PaperLayer, x: number, y: number, w: number, h: number, width: number, ru: string): PaperDef => ({ id, kind, layer, x, y, w, h, width, ru });

