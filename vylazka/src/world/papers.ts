/**
 * Наклейки (партнёр 19.11: «стикеры нужно оставить такими же, но сделать на них более детальное изображение»): слой stickers —
 * квадратные картинки STICKER_CELL px сеткой 4 в ряд; форма, кайма и место наклейки — прежние (world/props_craft.ts).
 */
export const STICKER_TILES = 23;
export const STICKER_CELL = 180;

/** uv картинки наклейки tile (0…STICKER_TILES−1): u — со сдвигом слоя, v растёт вверх; края поджаты на 3 px. */
export function stickerUv(tile: number): { u0: number; v0: number; u1: number; v1: number } {
  const layer = PAPER_LAYERS.indexOf('stickers');
  const t = ((Math.floor(tile) % STICKER_TILES) + STICKER_TILES) % STICKER_TILES;
  const x = (t % 4) * STICKER_CELL;
  const y = Math.floor(t / 4) * STICKER_CELL;
  const cut = 3;
  return {
    u0: PAPER_U0 + layer + (x + cut) / PAPER_W,
    u1: PAPER_U0 + layer + (x + STICKER_CELL - cut) / PAPER_W,
    v0: 1 - (y + STICKER_CELL - cut) / PAPER_H,
    v1: 1 - (y + cut) / PAPER_H,
  };
}

