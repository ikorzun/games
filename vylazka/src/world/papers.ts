export const PAPERS: Readonly<Record<string, PaperDef>> = Object.fromEntries(PAPER_LIST.map((p) => [p.id, p]));

/**
 * Сдвиг u, по которому шейдер узнаёт бумагу: у надписей и плакатов u лежит в 0…1 (атлас надписей), у
 * бумаги — PAPER_U0 + номер слоя + u. Материал у тех и других один (MAT.print).
 */
export const PAPER_U0 = 2;

/** Высота листа на стене при ширине width, м. */
export function paperHeight(p: PaperDef, width = p.width): number {
  return (width * p.h) / p.w;
}

/**
 * uv листа (v растёт вверх), u — со сдвигом слоя. Края поджаты на полтора пикселя: на уменьшенных
 * копиях слоя соседний лист не должен затекать в рамку.
 */
export function paperUv(id: string): { u0: number; v0: number; u1: number; v1: number; layer: number } {
  const p = PAPERS[id];
  if (!p) throw new Error(`нет такого листа: ${id}`);
  const layer = PAPER_LAYERS.indexOf(p.layer);
  const cut = 1.5;
  return {
    layer,
    u0: PAPER_U0 + layer + (p.x + cut) / PAPER_W,
    u1: PAPER_U0 + layer + (p.x + p.w - cut) / PAPER_W,
    v0: 1 - (p.y + p.h - cut) / PAPER_H,
    v1: 1 - (p.y + cut) / PAPER_H,
  };
}
