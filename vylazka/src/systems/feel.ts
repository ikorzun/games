/**
 * Кривая ощущений за сессию (K-11; предложение основной модели 17.11 09:50, принято словом партнёра 10:11 «Далее делай
 * предложенные рекомендации по гемплею»). Главная плоскость игры — ощущения (слова партнёра: «можно передать ощущения…
 * через его сжатие, расширение, через свет, через тень, через дребезжание… вещи являются всего лишь визуальным артефактом
 * наполнения мира»).
 *
 * В начале сессии мир почти не дышит; к концу он сжимается и плывёт:
 * - сжатие — свет и взгляд: луч фонаря уже, место собирается в более узком конусе взгляда, края кадра темнеют;
 * - «плывёт» — цвета кадра медленно расходятся и сходятся, строки кинескопа дрожат сильнее;
 * - звук — гул места густеет.
 * Вспомнил вещь — выдох (расширение): на несколько секунд луч и взгляд шире обычного, края светлеют, потом кривая
 * возвращается. Камера не качается: укачивание при ходьбе партнёр просил уменьшить (17.11 08:19), поэтому «плывёт» —
 * кадр, а не голова (противоречие 188 в реестре).
 *
 * Две кривые не складываются: у петли своя кривая по кругам (стёртость места); чем стёртее место, тем слабее сжатие сессии,
 * на последнем круге — вдвое (связь K-11 и M-12 в реестре).
 *
 * Кривая идёт по сессии игрока, а не по месту: в сне из сцен сессия — три сцены из разных мест, и кривая копится через все
 * три (противоречие 196 в реестре); время и вспомненное считает игра.
 *
 * Чистый TS: числа здесь, проверяются тестами; рисует это рендер (конус луча, конус взгляда, туннель, разлёт цветов).
 */
import { clamp, smoothstep } from '../core/math';

export interface FeelConfig {
  /** За сколько секунд сессии одно время доводит свою долю кривой до конца, с. */
  span: number;
  /** Доля кривой, которую дают воспоминания сессии (остальное — время). */
  recallShare: number;
  /** Сколько секунд держится выдох после воспоминания. */
  exhaleTime: number;
  /** Как быстро кривая догоняет цель, 1/с (и как быстро отпускает в карманном пространстве). */
  follow: number;
  /** К концу кривой: луч уже во столько раз, взгляд — во столько, темнота по краям кадра — такая. */
  beamTo: number;
  gazeTo: number;
  tunnelTo: number;
  /** На пике выдоха луч и взгляд шире во столько раз. */
  exhaleWide: number;
}

export const DEFAULT_FEEL: FeelConfig = {
  span: 480,
  recallShare: 0.6,
  exhaleTime: 9,
  follow: 0.25,
  beamTo: 0.8,
  gazeTo: 0.72,
  tunnelTo: 0.22,
  exhaleWide: 1.25,
};

export interface FeelInput {
  /** Секунды сессии. */
  time: number;
  /** Сколько воспоминаний вспомнено и сколько их в сессии всего. */
  done: number;
  count: number;
  /** Игрок в своём месте и сессия идёт; в карманном пространстве и в лимбо — нет (там кривая отпускает). */
  active: boolean;
  /** За сколько секунд время доводит свою долю до конца, если у сессии своя длина (сон из сцен короче); нет — cfg.span. */
  span?: number;
}

/** Что кривая делает с кадром и звуком сейчас. Нейтрально: beam 1, gaze 1, остальное 0. */
export interface FeelView {
  /** Множитель углов луча фонаря: меньше единицы — луч уже. */
  beam: number;
  /** Множитель конуса взгляда (место собирается только в нём): меньше единицы — уже. */
  gaze: number;
  /** 0..1 — темнота по краям кадра. */
  tunnel: number;
  /** 0..1 — кадр плывёт: цвета расходятся (медленную волну накладывает игра). */
  drift: number;
  /** 0..1 — строки кинескопа дрожат сверх обычного. */
  rattle: number;
  /** 0..1 — гул места густеет. */
  hum: number;
}

export const FEEL_NEUTRAL: FeelView = { beam: 1, gaze: 1, tunnel: 0, drift: 0, rattle: 0, hum: 0 };

export class SessionFeel {
  /** Сглаженная кривая, 0..1. */
  level = 0;
  /** Выдох, 0..1: 1 — сразу после воспоминания, дальше сходит к нулю за exhaleTime. */
  breath = 0;

  constructor(readonly cfg: FeelConfig = DEFAULT_FEEL) {}

  reset(): void {
    this.level = 0;
    this.breath = 0;
  }

  /** Вспомнил вещь: выдох. */
  exhale(): void {
    this.breath = 1;
  }

  /** Куда идёт кривая при таком ходе сессии (без сглаживания). */
  target(inp: FeelInput): number {
    if (!inp.active) return 0;
    const c = this.cfg;
    const byTime = clamp(inp.time / (inp.span ?? c.span), 0, 1);
    const byRecall = inp.count > 0 ? clamp(inp.done / inp.count, 0, 1) : 0;
    return smoothstep(0.1, 1, (1 - c.recallShare) * byTime + c.recallShare * byRecall);
  }

  update(dt: number, inp: FeelInput): void {
    const c = this.cfg;
    this.breath = Math.max(0, this.breath - dt / c.exhaleTime);
    this.level += (this.target(inp) - this.level) * (1 - Math.exp(-c.follow * dt));
  }

  /**
   * Что видно и слышно. wear — стёртость места по петле, 0..1: чем стёртее место, тем слабее сжатие сессии (на последнем
   * круге — вдвое). amp — сила кривой целиком (новичку она мягче: ему и так трудно находить вещи).
   */
  view(wear = 0, amp = 1): FeelView {
    const c = this.cfg;
    const k = this.level * (1 - 0.5 * clamp(wear, 0, 1)) * clamp(amp, 0, 1);
    // Выдох на пике сильнее и быстро сходит: квадрат.
    const out = this.breath * this.breath;
    const wide = 1 + (c.exhaleWide - 1) * out;
    return {
      beam: (1 - (1 - c.beamTo) * k * (1 - out)) * wide,
      gaze: (1 - (1 - c.gazeTo) * k * (1 - out)) * wide,
      tunnel: c.tunnelTo * k * (1 - out),
      drift: k * k * (1 - out),
      rattle: k * k * (1 - out),
      hum: k * (1 - 0.6 * out),
    };
  }
}
