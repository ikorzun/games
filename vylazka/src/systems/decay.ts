/**
 * Стирание. Слова партнёра (15.11): «Петля бесконечна, пока не сотрётся всё воспоминание: собери
 * тип деградации уровня и её кривую, которая влияет и на объекты и на архитектуру».
 *
 * Место — это воспоминание, и у него есть одна величина: стёртость w от 0 (помнится целиком) до 1
 * (стёрто). Она растёт с каждым кругом петли (то же место проходится заново), с каждой тронутой
 * вещью и каждый раз, когда Осыпь возвращает в начало. Когда w доходит до единицы, воспоминания
 * больше нет — и петля начинается с другого.
 *
 * Тип деградации — «в пыль и в кружево». Место не ломается и не ветшает: оно теряет вещество.
 * Слои уходят по очереди, и у каждого своя кривая (decayAt):
 *
 *   голоса людей     0,20 → 0,80   стихают: в месте, которое забывают, никого не остаётся
 *   мелочи           0,05 → 0,70   вещей сна на полках и на полу становится меньше
 *   краски           0,08 → 0,70   выцветают: место теряет цвет раньше, чем форму
 *   вещи             0,10 → 0,95   мебель стоит картонками, потом кружевом, потом её нет
 *   потолок          0,25 → 0,75   выпадает дырами, но не больше половины: сквозь дыры — небо
 *   берёзы           0,28 → 0,75   прорастают сквозь место («знак последних дней»)
 *   стены            0,50 → 0,95   редеют до кружева пятнами, но не больше трети
 *   пол              0,85 → 1,00   держится: под ногами кружево лишь местами
 *   гора             растёт всё время: туда слипается то, чего уже не восстановить
 *
 * Архитектура не исчезает (вариант A, docs/vylazka/levels.md; слова партнёра 16.11: «A…»): раньше потолок,
 * стены и пол стирались целиком, и вместе с темнотой и правилом взгляда от места оставалась половина
 * пространства («в нем просто нет половины пространства — стен, потолка, пола»). Теперь первыми уходят
 * вещи и краски, а план держится — и ещё его держит тихий слой: точки по рёбрам и углам (world/edges.ts).
 *
 * Сама кривая — S-образная: первые круги место почти цело, в середине рушится быстро, последние
 * нити держатся долго. Что именно стёрто у данного предмета, решают сид и номер предмета: у каждого
 * своя «прочность» 0..1, и он уходит, когда кривая его слоя поднимается выше неё. Поэтому от круга
 * к кругу пропадает одно и то же в одном и том же порядке — место узнаётся, пока от него что-то есть.
 *
 * Чистый TS: числа для рендера, сборки уровня и игры считаются здесь и проверяются тестами.
 */
import { hash01 } from '../core/rng';
import { FORM_GONE, FORM_LACE, FORM_REAL } from './illusions';
import type { Form } from './illusions';

/** На сколько вырастает стёртость. */
export const WEAR = {
  /** Круг пройден (сессия закончена в этом месте). */
  lap: 0.14,
  /** Вещь тронута и рассыпалась. */
  touch: 0.004,
  /** Вещь стёрта совсем (прошла все ступени). */
  erased: 0.006,
  /** Осыпь дотянулась и вернула в начало. */
  caught: 0.02,
} as const;

const clamp01 = (v: number): number => Math.max(0, Math.min(1, v));
const smooth = (a: number, b: number, v: number): number => {
  const t = clamp01((v - a) / (b - a));
  return t * t * (3 - 2 * t);
};

/** Сколько от слоя архитектуры может стереться (вариант A): потолок — дырами до половины, стены — до трети, пол — местами. */
export const CEIL_MAX = 0.55;
export const WALLS_MAX = 0.3;
export const FLOOR_MAX = 0.12;

export interface Decay {
  /** Сама стёртость 0..1. */
  wear: number;
  /** Сколько от места осталось, 0..1: S-образная кривая — одно число «на глаз» для подписей и звука. */
  integrity: number;
  /** Доля предметов обстановки, от которых осталось одно кружево (или меньше). */
  lace: number;
  /** Доля предметов, которых уже нет. */
  gone: number;
  /** Во сколько раз чаще обычного предмет стоит картонкой (множитель доли плоских вещей). */
  flats: number;
  /** Доля мелких вещей сна, которые ещё есть. */
  clutter: number;
  /** Потолок: 0 — цел, 1 — его нет (по варианту A — не больше CEIL_MAX). */
  ceiling: number;
  /** Стены: 0 — целы, 1 — одно кружево (не больше WALLS_MAX). */
  walls: number;
  /** Пол: 0 — цел, 1 — одно кружево (не больше FLOOR_MAX). */
  floor: number;
  /** Краски: 0 — свои, 1 — выцвели до серого. */
  paint: number;
  /** Насколько слышны люди, 0..1. */
  voices: number;
  /** Сколько берёз проросло сквозь место, 0..1 от полной рощи. */
  birches: number;
  /** Гора слипшегося: 0 — нет, 1 — кучка, 2 — гора, 3 — большая гора. */
  mound: 0 | 1 | 2 | 3;
}

/** Все кривые разом. */
export function decayAt(wear: number): Decay {
  const w = clamp01(wear);
  return {
    wear: w,
    integrity: 1 - smooth(0.08, 0.92, w),
    lace: 0.97 * smooth(0.1, 0.85, w),
    gone: 0.92 * smooth(0.35, 1.0, w) ** 1.3,
    flats: 1 + 2.5 * smooth(0.05, 0.6, w),
    clutter: 1 - smooth(0.05, 0.7, w),
    ceiling: CEIL_MAX * smooth(0.25, 0.75, w),
    walls: WALLS_MAX * smooth(0.5, 0.95, w),
    floor: FLOOR_MAX * smooth(0.85, 1.0, w),
    paint: smooth(0.08, 0.7, w),
    voices: 1 - smooth(0.2, 0.8, w),
    birches: smooth(0.28, 0.75, w),
    mound: w < 0.1 ? 0 : w < 0.38 ? 1 : w < 0.7 ? 2 : 3,
  };
}

/** «Прочность» предмета 0..1: чем меньше, тем раньше он стирается. Одна и та же при любом w. */
export function strength(id: number, seed: number): number {
  return hash01(id * 53 + 11, 0x77, seed ^ 0x0decade);
}

/**
 * На какой ступени стоит предмет обстановки в начале круга: настоящий, кружево или его уже нет.
 * (Картонкой и проекцией предмет становится иначе: картонки ставит сборка уровня — их доля растёт
 * с w, — а проекция получается только из тронутой картонки.)
 */
export function startForm(id: number, seed: number, wear: number): Form {
  const d = decayAt(wear);
  const s = strength(id, seed);
  if (s < d.gone) return FORM_GONE;
  if (s < d.lace) return FORM_LACE;
  return FORM_REAL;
}

/** Мелкая вещь сна ещё есть? */
export function keepsClutter(index: number, seed: number, wear: number): boolean {
  return hash01(index * 29 + 5, 0x33, seed ^ 0x0c1a77e2) < decayAt(wear).clutter;
}

/** Сколько кругов место выдержит ещё, если ничего не трогать. */
export function lapsLeft(wear: number): number {
  return Math.max(0, Math.ceil((1 - clamp01(wear)) / WEAR.lap - 1e-9));
}

/** Стёрто ли воспоминание совсем: следующий круг — уже в другом. */
export function erased(wear: number): boolean {
  return wear >= 1 - 1e-9;
}
